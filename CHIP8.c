void reset() {
  pc = 0x200;
  opcode = 0;
  I = 0;
  sp = 0;
  delay_timer = 0;
  sound_timer = 0;

  for (int i = 0; i < 4096; i++) {
    memory[i] = 0;
  }

  for (int i = 0; i < 2046; i++) {
    graphics[i] = 0;
  }

  for (int i = 0; i < 16; i++) {
    V[i] = 0;
    stack[i] = 0;
    key[i] = 0;
  }
}

bool load(const char *filepath) {
  reset();

  FILE *fptr = fopen(filepath, "rb");
  if (!fptr)
    return false;

  fseek(fptr, 0, SEEK_END);
  long rom_size = ftell(fptr);
  fread(&memory[pc], sizeof(uint16_t), rom_size, fptr);

  fclose(fptr);

  return true;
}

